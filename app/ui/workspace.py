from PySide6.QtCore import Signal
from PySide6.QtWidgets import QWidget, QVBoxLayout, QComboBox, QListWidget, QProgressBar, QPushButton, QScrollArea, QHBoxLayout, QLineEdit, QCheckBox, QPlainTextEdit, QApplication, QTabWidget
from app.ui.components import panel, label, pending
from app.ui.primary_button import PrimaryButton
from app.features.subtitles.model import subtitle_time
from app.ui.subtitle_editor import SubtitleEditor


class SubtitlePanel(QWidget):
    requested = Signal(str, str)
    cancelled = Signal()

    def __init__(self):
        super().__init__()
        self.setMinimumWidth(310)
        outer = QVBoxLayout(self)
        outer.setContentsMargins(0, 0, 0, 0)
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setFrameShape(QScrollArea.Shape.NoFrame)
        self.tabs = QTabWidget()
        outer.addWidget(self.tabs)
        self.tabs.addTab(scroll, "자동 생성")
        self.editor = SubtitleEditor()
        self.tabs.addTab(self.editor, "검수·수정")
        frame, layout = panel()
        scroll.setWidget(frame)
        layout.setContentsMargins(14, 12, 14, 12)
        layout.setSpacing(8)
        layout.addWidget(label("자동 자막", "heading"))
        layout.addWidget(label("LOCAL AI · CPU", "badge"))
        self.language = QComboBox()
        for name, code in (("한국어", "ko"), ("자동 감지", "auto"), ("영어", "en"), ("일본어", "ja")):
            self.language.addItem(name, code)
        self.language.setAccessibleName("음성 인식 언어")
        settings = QHBoxLayout()
        settings.addWidget(self.language)
        self.model = QComboBox()
        for name, code in (("Tiny · 빠른 확인", "tiny"), ("Base · 빠름", "base"), ("Small · 빠름", "small"), ("Turbo · 정밀", "large-v3-turbo")):
            self.model.addItem(name, code)
        self.model.setCurrentIndex(3)
        self.model.setAccessibleName("음성 인식 모델")
        self.language.setMinimumContentsLength(4)
        self.model.setMinimumContentsLength(4)
        self.language.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
        self.model.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
        self.language.setToolTip("인식 언어 · 한국어 / 자동 / 영어 / 일본어")
        self.model.setToolTip("Tiny/Base/Small: 작은 모델 · Turbo: 상위 모델, CPU 사용량과 메모리 사용이 더 큽니다. 품질 보장은 아닙니다.")
        settings.addWidget(self.model)
        layout.addLayout(settings)
        layout.addWidget(label("등장하는 이름·용어 (선택)", "muted"))
        self.terms = QLineEdit()
        self.terms.setMaxLength(400)
        self.terms.setPlaceholderText("예: 라겸, 경희")
        self.terms.setAccessibleName("실제 등장하는 이름과 전문 용어 힌트")
        self.terms.setToolTip("실제로 등장하는 단어만 쉼표로 입력하세요. 인식 힌트이며 강제 치환이나 정확도 보장은 아닙니다.")
        layout.addWidget(self.terms)
        self.skip_silence = QCheckBox("조용한 구간 건너뛰기 · 빠름")
        self.skip_silence.setToolTip("기본값은 꺼짐입니다. 켜면 원거리 목소리나 짧은 말이 누락될 수 있습니다. 앞부분이 빠지면 끄고 다시 생성하세요.")
        layout.addWidget(self.skip_silence)
        self.generate = PrimaryButton("✦  자동 자막 생성")
        self.generate.setFixedHeight(36)
        self.generate.setEnabled(False)
        self.generate.clicked.connect(lambda: self.requested.emit(self.model.currentData(), self.language.currentData()))
        actions = QHBoxLayout()
        actions.addWidget(self.generate)
        self.cancel_button = QPushButton("취소")
        self.cancel_button.setEnabled(False)
        self.cancel_button.clicked.connect(self.cancelled.emit)
        self.cancel_button.setToolTip("자막 생성 취소 · 기존 자막 유지")
        self.cancel_button.setFixedHeight(36)
        actions.addWidget(self.cancel_button)
        layout.addLayout(actions)
        self.progress = QProgressBar()
        self.progress.setRange(0, 0)
        self.progress.setTextVisible(False)
        self.progress.setFixedHeight(5)
        self.progress.hide()
        layout.addWidget(self.progress)
        self.status = label("음성이 있는 영상을 선택하세요.", "muted")
        layout.addWidget(self.status)
        result_bar = QHBoxLayout()
        result_bar.addWidget(label("자막 결과", "heading"))
        result_bar.addStretch()
        self.copy_all = QPushButton("전체 복사")
        self.copy_all.setEnabled(False)
        self.copy_all.setToolTip("시간과 자막 문장을 전체 복사합니다.")
        self.copy_all.clicked.connect(lambda: QApplication.clipboard().setText(self.results.toPlainText()))
        result_bar.addWidget(self.copy_all)
        layout.addLayout(result_bar)
        self.results = QPlainTextEdit()
        self.results.setObjectName("subtitleText")
        self.results.setReadOnly(True)
        self.results.setMinimumHeight(110)
        self.results.setPlaceholderText("생성된 자막이 없습니다.")
        self.results.setAccessibleName("자막 결과 · 드래그 선택, Ctrl+C 또는 우클릭으로 복사 · 읽기 전용")
        layout.addWidget(self.results, 1)
        layout.addWidget(label("첫 사용은 모델 다운로드가 필요합니다. 영상은 업로드하지 않습니다.\n검수·수정 탭에서 문장과 시간을 고치고 SRT로 출력하세요.", "muted"))


    def set_busy(self, busy):
        self.editor.setEnabled(not busy)
        self.language.setEnabled(not busy)
        self.model.setEnabled(not busy)
        self.terms.setEnabled(not busy)
        self.skip_silence.setEnabled(not busy)
        self.generate.setEnabled(False)
        self.cancel_button.setEnabled(busy)
        self.progress.setVisible(busy)
        self.generate.setText("생성 중…" if busy else "✦  자동 자막 생성")

    def show_segments(self, segments, language="ko", select=-1):
        text = "\n\n".join(f"{subtitle_time(s['start'])} → {subtitle_time(s['end'])}\n{s['text']}" for s in segments)
        self.results.setPlainText(text)
        self.copy_all.setEnabled(bool(text))
        self.editor.show_segments(segments, language, select)
